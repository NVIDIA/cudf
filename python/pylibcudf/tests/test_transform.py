@cache
def get_transform_udf(binary_type, use_numba, num_outputs):
    """Get an embedded or Numba-compiled UDF, skipping missing Numba on demand."""
    fragment_type = {
        "ptx": plc.udf.LTOBinaryType.PTX,
        "ltoir": plc.udf.LTOBinaryType.LTO_IR,
    }[binary_type]
    if use_numba:
        numba = pytest.importorskip("numba")
        cuda = pytest.importorskip("numba.cuda")

        if num_outputs == 1:

            @cuda.jit(device=True, lto=binary_type == "ltoir")
            def op(a, b, c):
                return (a + b) * c

            signature = (numba.float64, numba.float64, numba.float64)
        else:

            @cuda.jit(device=True, lto=binary_type == "ltoir")
            def op(difference, a, b):
                difference[0] = a - b
                return a + b

            signature = (
                numba.types.CPointer(numba.float32),
                numba.float64,
                numba.float64,
            )

        compiled = op.compile_device(signature, return_type=numba.float64)
        cc = tuple(cuda.get_current_device().compute_capability)
        if binary_type == "ltoir":
            module = bytes(compiled.library.get_ltoir(cc=cc))
        else:
            module = compiled.library.get_asm_str(cc=cc).encode()
        symbol = compiled.fndesc.llvm_func_name
    else:
        ptx_symbol, ptx, symbol, lto_ir12, lto_ir13 = {
            1: (
                _TRANSFORM_UDF_PTX_SYMBOL,
                _TRANSFORM_UDF_PTX,
                _TRANSFORM_UDF_LTO_IR_SYMBOL,
                _TRANSFORM_UDF_LTO_IR_CUDA12,
                _TRANSFORM_UDF_LTO_IR_CUDA13,
            ),
            2: (
                _MULTI_OUTPUT_UDF_PTX_SYMBOL,
                _MULTI_OUTPUT_UDF_PTX,
                _MULTI_OUTPUT_UDF_LTO_IR_SYMBOL,
                _MULTI_OUTPUT_UDF_LTO_IR_CUDA12,
                _MULTI_OUTPUT_UDF_LTO_IR_CUDA13,
            ),
        }[num_outputs]
        if binary_type == "ptx":
            symbol, module = ptx_symbol, ptx
        else:
            status, version = runtime.cudaRuntimeGetVersion()
            assert status == runtime.cudaError_t.cudaSuccess
            module = {12: lto_ir12, 13: lto_ir13}[version // 1000]

    return plc.udf.TransformUDF(
        symbol=symbol,
        fragments=(plc.udf.LTOFragment(fragment_type, module),),
    )


@pytest.mark.parametrize("binary_type", ["ptx", "ltoir"])
@pytest.mark.parametrize("use_numba", [False, True], ids=["embedded", "numba"])
def test_transform_udf(binary_type, use_numba):
    _check_transform_udf(
        get_transform_udf(binary_type, use_numba, num_outputs=1)
    )


@pytest.mark.parametrize("values", [[], [1.0, 2.0, 3.0]])
@pytest.mark.parametrize("binary_type", ["ptx", "ltoir"])
@pytest.mark.parametrize("use_numba", [False, True], ids=["embedded", "numba"])
def test_transform_single_output_table(values, binary_type, use_numba):
    input = plc.Column.from_arrow(pa.array(values, type=pa.float64()))
    got = plc.transform.transform(
        [input, input, input],
        udf=get_transform_udf(binary_type, use_numba, num_outputs=1),
        output_type=[plc.DataType(plc.TypeId.FLOAT64)],
        null_policy=plc.types.OutputNullability.PRESERVE,
    )
    assert isinstance(got, plc.Table)
    assert got.num_columns() == 1
    assert_column_eq(
        pa.array([2 * value * value for value in values], type=pa.float64()),
        got.columns()[0],
    )


@pytest.mark.parametrize("values", [[], [1.0, 2.0, 3.0]])
@pytest.mark.parametrize("binary_type", ["ptx", "ltoir"])
@pytest.mark.parametrize("use_numba", [False, True], ids=["embedded", "numba"])
def test_transform_multiple_outputs(values, binary_type, use_numba):
    got = plc.transform.transform(
        [
            plc.Column.from_arrow(pa.array(values, type=pa.float64())),
            plc.Column.from_arrow(pa.array([0.5])),
        ],
        udf=get_transform_udf(binary_type, use_numba, num_outputs=2),
        output_type=[
            plc.DataType(plc.TypeId.FLOAT64),
            plc.DataType(plc.TypeId.FLOAT32),
        ],
        null_policy=plc.types.OutputNullability.PRESERVE,
    )
    assert isinstance(got, plc.Table)
    assert got.num_columns() == 2
    assert_column_eq(
        pa.array([value + 0.5 for value in values], type=pa.float64()),
        got.columns()[0],
    )
    assert_column_eq(
        pa.array([value - 0.5 for value in values], type=pa.float32()),
        got.columns()[1],
    )


@pytest.mark.parametrize("use_numba", [False, True], ids=["embedded", "numba"])
def test_transform_mixed_fragments(use_numba):
    udfs = (
        get_transform_udf("ptx", use_numba, num_outputs=1),
        get_transform_udf("ltoir", use_numba, num_outputs=1),
    )
    fragments = udfs[0].fragments + udfs[1].fragments
    for udf in udfs:
        _check_transform_udf(plc.udf.TransformUDF(udf.symbol, fragments))


def _check_transform_udf(udf):
    A = 5.0
    B = 20.0
    C = 0.5

    expect = pa.array([(A + B) * C] * 100)
    inputs = [
        plc.Column.from_arrow(pa.array([A] * 100)),
        plc.Column.from_arrow(pa.array([B] * 100)),
        plc.Column.from_arrow(pa.array([C])),
    ]
    got = plc.transform.transform(
        inputs,
        udf=udf,
        output_type=plc.DataType(plc.TypeId.FLOAT64),
        null_policy=plc.types.OutputNullability.PRESERVE,
    )
    assert isinstance(got, plc.Table)
    assert got.num_columns() == 1
    assert_column_eq(expect, got.columns()[0])
