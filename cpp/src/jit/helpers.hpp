/**
 * @brief Make code generated by row IR callable through a kernel's operation macro.
 *
 * The generated code is compiled as it is: instead of having the source parser rename the first
 * function it finds, which may be a callee declaration, the macro through which the kernel calls
 * the operation is defined as a call of the generated function.
 *
 * @param cuda_source The generated code, which defines `function_name` at global scope
 * @param operation_macro The macro through which the kernel calls the operation
 * @param function_name The name of the generated function
 * @return The code to compile as the kernel's operation
 */
std::string define_operation(std::string const& cuda_source,
                             std::string_view operation_macro,
                             std::string_view function_name);

