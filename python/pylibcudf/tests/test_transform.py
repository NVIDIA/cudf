@cache
def get_transform_udf(num_outputs):
    ptx_symbol, ptx = {
        1: (
            _TRANSFORM_UDF_PTX_SYMBOL,
            _TRANSFORM_UDF_PTX,
        ),
        2: (
            _MULTI_OUTPUT_UDF_PTX_SYMBOL,
            _MULTI_OUTPUT_UDF_PTX,
        ),
    }[num_outputs]

    return plc.udf.TransformUDF(
        symbol=ptx_symbol,
        fragments=(plc.udf.LTOFragment(plc.udf.LTOBinaryType.PTX, ptx),),
    )


@pytest.mark.parametrize("values", [[], [1.0, 2.0, 3.0]])
def test_transform_single_output_table(values):
    input = plc.Column.from_arrow(pa.array(values, type=pa.float64()))
    got = plc.transform.transform(
        [input, input, input],
        udf=get_transform_udf(num_outputs=1),
        output_type=[plc.DataType(plc.TypeId.FLOAT64)],
        null_policy=plc.types.OutputNullability.PRESERVE,
    )
    assert isinstance(got, plc.Table)
    assert got.num_columns() == 1
    assert_column_eq(
        pa.array([2 * value * value for value in values], type=pa.float64()),
        got.columns()[0],
    )


@pytest.mark.parametrize("values", [[], [1.0, 2.0, 3.0]])
def test_transform_multiple_outputs(values):
    got = plc.transform.transform(
        [
            plc.Column.from_arrow(pa.array(values, type=pa.float64())),
            plc.Column.from_arrow(pa.array([0.5])),
        ],
        udf=get_transform_udf(num_outputs=2),
        output_type=[
            plc.DataType(plc.TypeId.FLOAT64),
            plc.DataType(plc.TypeId.FLOAT32),
        ],
        null_policy=plc.types.OutputNullability.PRESERVE,
    )
    assert isinstance(got, plc.Table)
    assert got.num_columns() == 2
    assert_column_eq(
        pa.array([value + 0.5 for value in values], type=pa.float64()),
        got.columns()[0],
    )
    assert_column_eq(
        pa.array([value - 0.5 for value in values], type=pa.float32()),
        got.columns()[1],
    )
